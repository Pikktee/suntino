let activeUiLang = UI_FALLBACK_LANG;

// Liste der wählbaren Sprach-Codes (ohne "auto").
function uiLanguageCodes() {
  return UI_LANGUAGES.map((l) => l.code);
}

// Erkennt die passende UI-Sprache aus Browser/OS, sonst Fallback.
function detectUiLang() {
  const nav = typeof navigator === 'undefined' ? {} : navigator;
  const candidates = [nav.language, ...(nav.languages || [])].filter(Boolean);
  for (const cand of candidates) {
    const base = String(cand).split('-')[0].toLowerCase();
    if (MESSAGES[base]) return base;
  }
  return UI_FALLBACK_LANG;
}

// Wandelt eine Einstellung ('auto' | Sprachcode) in einen konkreten Code um.
function resolveUiLang(pref) {
  if (pref && pref !== 'auto' && MESSAGES[pref]) return pref;
  if (!pref || pref === 'auto') return detectUiLang();
  return UI_FALLBACK_LANG;
}

// Setzt die aktive UI-Sprache (validiert gegen vorhandene Kataloge).
function setActiveUiLang(lang) {
  activeUiLang = MESSAGES[lang] ? lang : UI_FALLBACK_LANG;
  return activeUiLang;
}

function currentUiLang() {
  return activeUiLang;
}

// Übersetzt einen Schlüssel; {platzhalter} werden aus vars ersetzt.
function t(key, vars) {
  return tIn(activeUiLang, key, vars);
}

// Wie t(), aber für eine explizit angegebene Sprache (z. B. zum Vergleich,
// ob ein Wert noch einem Default in irgendeiner Sprache entspricht).
function tIn(lang, key, vars) {
  const table = MESSAGES[lang] || MESSAGES[UI_FALLBACK_LANG];
  let str = table[key];
  if (str == null) str = MESSAGES[UI_FALLBACK_LANG][key];
  if (str == null) return key;
  if (vars) str = str.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return str;
}
